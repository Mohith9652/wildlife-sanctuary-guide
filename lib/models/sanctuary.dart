  final String id;
  final String name;
  final String location;
  final String state;
  final String description;
  final String imageUrl;
  final List<String> highlights;

  const Sanctuary({
    required this.id,
    required this.name,
    required this.location,
    required this.state,
    required this.description,
    required this.imageUrl,
    required this.highlights,
  });
}
